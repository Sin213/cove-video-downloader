#!/usr/bin/env node
/**
 * Copy the renderer's third-party assets out of node_modules into
 * renderer/vendor/ so the packaged app never reaches the network to draw its
 * own UI. Previously React, ReactDOM, Babel-standalone and the Geist fonts
 * were <script src="https://unpkg.com/..."> / Google Fonts links, which meant
 * an offline, DNS-blocked or captive-portal launch produced a blank window.
 *
 * Runs from `prestart` and `prepack`, and is idempotent.
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT       = path.join(__dirname, '..');
const VENDOR_DIR = path.join(ROOT, 'renderer', 'vendor');
const FONT_DIR   = path.join(VENDOR_DIR, 'fonts');

const ASSETS = [
  ['react/umd/react.production.min.js',          'react.production.min.js'],
  ['react-dom/umd/react-dom.production.min.js',  'react-dom.production.min.js'],
  ['@babel/standalone/babel.min.js',             'babel.min.js'],
];

const FONTS = [
  ['geist/dist/fonts/geist-sans/Geist-Variable.woff2',     'Geist-Variable.woff2'],
  ['geist/dist/fonts/geist-mono/GeistMono-Variable.woff2', 'GeistMono-Variable.woff2'],
];

function copy(rel, destDir, destName) {
  const src = path.join(ROOT, 'node_modules', rel);
  if (!fs.existsSync(src)) {
    console.error(
      `[vendor] missing ${rel}\n` +
      `         Run \`npm install\` first - the renderer cannot load without it.`);
    process.exitCode = 1;
    return false;
  }
  const dest = path.join(destDir, destName);
  fs.mkdirSync(destDir, { recursive: true });
  fs.copyFileSync(src, dest);
  const kb = (fs.statSync(dest).size / 1024).toFixed(0);
  console.log(`[vendor] ${destName} (${kb} KB)`);
  return true;
}

// Both Geist faces are variable fonts, so a single file per family covers the
// 300-700 range the UI asks for.
const GEIST_CSS = `/* Generated by scripts/vendor-assets.js - do not edit. */
@font-face {
  font-family: 'Geist';
  font-style: normal;
  font-weight: 300 700;
  font-display: swap;
  src: url('./Geist-Variable.woff2') format('woff2-variations');
}
@font-face {
  font-family: 'Geist Mono';
  font-style: normal;
  font-weight: 300 700;
  font-display: swap;
  src: url('./GeistMono-Variable.woff2') format('woff2-variations');
}
`;

let ok = true;
for (const [rel, name] of ASSETS) ok = copy(rel, VENDOR_DIR, name) && ok;
for (const [rel, name] of FONTS)  ok = copy(rel, FONT_DIR,   name) && ok;

if (ok) {
  fs.writeFileSync(path.join(FONT_DIR, 'geist.css'), GEIST_CSS, 'utf8');
  console.log('[vendor] geist.css');
}

if (!ok) {
  console.error('[vendor] one or more assets are missing - see above.');
  process.exit(1);
}
console.log('[vendor] renderer assets are self-contained.');
